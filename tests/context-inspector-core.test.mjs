import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {createWorld,execute} from '../packages/core/engine.mjs';
import {registry} from '../packages/modules/index.mjs';
import {selectLore} from '../packages/ai/context.mjs';
import {inspectContext} from '../packages/ai/inspect.mjs';
const pack=()=>{const p=JSON.parse(readFileSync(new URL('../packs/neutral.json',import.meta.url)));delete p.modules['world.schedule'];p.modules['story.facts']='0.1.0';return p;};
const fixture=p=>{let s=createWorld(p,registry,'inspect');const act=(id,type,args)=>{const r=execute(s,{id,type,args,actorId:p.playerId,expectedRevision:s.revision},p,registry);s=r.state;r.turn.status='complete';r.turn.narrative='Ada remembers the archive at sunset.';return r.turn;};const t=act('heard','social.speak',{target:'ada',text:'My favorite color is teal'});t.generatedFacts=[{id:'heard.fact-0',subject:'ada',text:'The archive opens at sunset.',quote:'the archive at sunset',source:'heard',knownBy:['player','ada']}];act('vow','social.speak',{target:'ada',text:'I promise to bring coffee tomorrow'});return {get state(){return s;},act};};
test('selectLore records privacy, cap and truncation exclusions with reasons',()=>{const p=pack(),s=fixture(p).state;
 p.lorebook=[...Array(6)].map((_,i)=>({id:`lore-${i}`,text:`Archive note ${i}.`,keys:['archive'],scope:'world',knownBy:'public'}));
 p.lorebook.push({id:'secret',text:'Ada hides a blue notebook.',keys:['archive','notebook'],scope:'character',character:'ada',knownBy:['ada']},{id:'long',text:'x'.repeat(400),keys:['archive'],scope:'world',knownBy:'public',location:s.actors.brin.location});
 const trace=selectLore(s,p,'brin','archive');
 assert.ok(trace.selected.some(e=>e.id==='long'&&e.truncated&&e.text.endsWith('…')));
 assert.ok(!trace.selected.some(e=>e.id==='secret'));
 assert.equal(trace.selected.length,4);
 assert.ok(trace.omitted.some(o=>o.id==='secret'&&/private/.test(o.reason)));
 assert.equal(trace.omitted.filter(o=>/cap:/.test(o.reason)).length,3);
 const ada=selectLore(s,p,'ada','archive');
 assert.ok(ada.selected.some(e=>e.id==='secret'));
});
test('inspectContext reports persona, included and excluded pools with reasons',()=>{const p=pack(),h=fixture(p);
 p.facts=[{id:'public-fact',text:'The workshop is open late.',knownBy:'public'},{id:'hidden-fact',text:'Ada hides a blue notebook.',knownBy:['ada']}];
 for(let i=0;i<12;i++){const t=h.act(`plain${i}`,'social.speak',{target:'ada',text:`the archive is locked today, part ${i}`});t.generatedFacts=[];}
 const s=h.state;
 s.modules['story.scenes']={plans:[],history:[],memories:[...Array(9)].map((_,i)=>({scene:`s${i}`,text:`Scene memory ${i}.`,knownBy:'public'}))};
 s.modules['story.scenes'].memories.push({scene:'priv',text:'Private scene note.',knownBy:['ada']});
 const d=inspectContext(s,p,'brin','archive');
 assert.equal(d.owner,'brin');assert.ok(d.actors.some(a=>a.id==='ada'));
 assert.ok(d.facts.included.some(f=>f.id==='public-fact'));
 assert.ok(d.facts.excluded.some(f=>f.id==='hidden-fact'&&/private/.test(f.reason)));
 assert.ok(d.generated.included.length===0&&d.generated.excluded.some(f=>f.id==='heard.fact-0'&&/private/.test(f.reason)));
 assert.ok(d.sceneMemories.excludedByCap.length>=1&&d.sceneMemories.excludedPrivate.some(m=>m.text==='Private scene note.'));
 assert.ok(d.lore.selected.every(e=>!/private/.test(e.reason))&&JSON.stringify(d.promptMessages).length>500);
 assert.ok(!/blue notebook|Private scene note/.test(JSON.stringify(d.promptMessages)));
 assert.throws(()=>inspectContext(s,p,'stranger',''),/owner/);
 const ada=inspectContext(s,p,'ada','archive');
 assert.ok(ada.generated.included.some(f=>f.id==='heard.fact-0'));
 assert.ok(!ada.generated.excluded.some(f=>f.id==='heard.fact-0'));
 assert.ok(ada.statements.included.length>0&&ada.statements.excludedPrivate.length===0);
 assert.ok(ada.statements.excludedByCap.length>=8&&ada.statements.excludedByCap.every(m=>/cap:/.test(m.reason)));
 assert.ok(ada.facts.included.some(f=>f.id==='hidden-fact')&&ada.facts.excluded.every(f=>f.id!=='hidden-fact'));
});
